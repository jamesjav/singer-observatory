import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';

const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 2 });
const report = { checks: [], errors: [] };
const check = (name, condition) => { assert.ok(condition, name); report.checks.push(name); };
const url = process.env.APP_URL ?? 'http://127.0.0.1:5192/';
page.on('pageerror', error => report.errors.push(error.message));
page.on('console', message => { if (/THREE.WebGLProgram|Shader Error/i.test(message.text())) report.errors.push(message.text()); });
try {
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 30000 });
  if (await page.getByTestId('enter-observatory').isVisible().catch(() => false)) {
    await page.getByTestId('enter-observatory').click();
    await page.getByTestId('opening-prologue').waitFor({ state: 'detached', timeout: 5000 });
  }
  await page.locator('.loading-status').waitFor({ state: 'detached', timeout: 30000 });
  await page.waitForFunction(() => document.querySelector('[data-testid=news-source-state]')?.dataset.mode === 'live', { timeout: 20000 });
  check('production omits the diagnostic engine global', await page.evaluate(() => window.__observatory === undefined));
  check('production audio is strictly uninitialized by default', await page.getByTestId('sound-toggle').getAttribute('data-audio-initialized') === 'false');
  await page.waitForFunction(() => document.querySelectorAll('.surface-label').length >= 3 && document.querySelector('.instrument-panel .weather-slot')?.dataset.weatherState === 'live', null, { timeout: 22000 });
  await page.mouse.move(3, 500);
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.surface-signals')).opacity === '1');
  check('production defaults to readable news and quake annotations', await page.locator('.surface-label:not(.seismic-label)').count() >= 2 && await page.locator('.seismic-label').count() === 1);
  await page.screenshot({ path: 'scripts/artifacts/signals-default-final.png', fullPage: true });
  const selectedId = await page.locator('.surface-label:not(.seismic-label)').first().getAttribute('data-signal-id');
  await page.locator(`[data-news-id="${selectedId}"]`).click();
  await page.mouse.move(3, 500);
  await page.waitForTimeout(1500);
  await page.waitForFunction(() => document.querySelector('.surface-label.is-fixed a') && ['live','cached'].includes(document.querySelector('.instrument-panel .weather-slot')?.dataset.weatherState), null, { timeout: 20000 });
  check('production list click fixes a leader, original link, weather and day/night', /昼面|夜面|晨昏带/.test(await page.locator('.instrument-panel .weather-slot').innerText()) && await page.locator('.instrument-panel .weather-values').count() === 1);
  check('weather leader masks text instead of striking through the headline', await page.locator('.selection-guide>path').getAttribute('mask') !== null && (await page.locator('.selection-guide mask path').getAttribute('d')).includes('M '));
  await page.screenshot({ path: 'scripts/artifacts/signals-focused-final.png', fullPage: true });
  await page.getByRole('button', { name: '← 返回噪音流' }).click();
  await page.getByTestId('cosmic-scale').click();
  check('production scale telemetry is expandable', (await page.locator('.cosmic-scale').innerText()).includes('光秒'));
  await page.getByTestId('cosmic-scale').click();
  await page.mouse.move(720, 500);
  await page.keyboard.press('h');
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.hud')).opacity === '0');
  check('production quiet mode hides the HUD and fades annotations', await page.locator('.hud').evaluate(element => element.inert) && await page.locator('.surface-signals').evaluate(element => getComputedStyle(element).opacity === '0'));
  await page.mouse.move(2, 500);
  await page.waitForFunction(() => !document.querySelector('main').classList.contains('is-quiet') && getComputedStyle(document.querySelector('.hud')).opacity === '1');
  await page.getByTestId('foil-preview').click();
  await page.getByTestId('release-foil').click();
  await page.waitForFunction(() => document.querySelector('main').dataset.phase === 'archived', { timeout: 16000 });
  check('production completes the dimensional performance', (await page.getByTestId('dimensional-status').innerText()).includes('二维化完成 · 表面噪音归零 · 进程归档'));
  await page.screenshot({ path: 'scripts/artifacts/production-archived.png' });
  await page.getByTestId('restore-dimension').click();
  await page.waitForFunction(() => document.querySelector('main').dataset.phase === 'idle' && getComputedStyle(document.querySelector('.hud')).opacity === '1');
  await page.getByLabel('表面噪音', { exact: true }).uncheck();
  await page.getByLabel('地壳微震', { exact: true }).uncheck();
  await page.getByLabel('地表标注', { exact: true }).uncheck();
  await page.mouse.click(730, 480);
  await page.waitForFunction(() => ['live', 'cached', 'unavailable'].includes(document.querySelector('.instrument-panel .weather-slot')?.dataset.weatherState), { timeout: 20000 });
  report.weather = await page.locator('.instrument-panel .weather-slot').innerText();
  report.weatherState = await page.locator('.instrument-panel .weather-slot').getAttribute('data-weather-state');
  check('production restored surface picks receive real weather', report.weatherState === 'live' && report.weather.includes('hPa'));
  await page.getByLabel('风场矢量', { exact: true }).check();
  await page.waitForFunction(() => ['live', 'cached', 'unavailable'].includes(document.querySelector('[data-wind-state]')?.dataset.windState), { timeout: 20000 });
  report.wind = await page.locator('[data-wind-state]').innerText();
  check('production real wind data remains operational', report.wind.includes('60'));
  await page.getByTestId('sound-toggle').click();
  await page.waitForFunction(() => document.querySelector('[data-testid=sound-toggle]').getAttribute('aria-pressed') === 'true');
  await page.getByTestId('sound-toggle').click();
  await page.waitForFunction(() => document.querySelector('[data-testid=sound-toggle]').getAttribute('aria-pressed') === 'false');
  check('production sound enables and mutes without errors', await page.getByTestId('sound-toggle').getAttribute('data-audio-initialized') === 'true');
  await page.getByLabel('表面噪音', { exact: true }).check();
  await page.getByLabel('地壳微震', { exact: true }).check();
  await page.getByLabel('地表标注', { exact: true }).check();
  const response = await page.request.get(`${url}api/news`);
  const snapshot = await response.json();
  report.sources = snapshot.sources;
  report.news = { count: snapshot.events.length, seismic: snapshot.events.filter(event => event.kind === 'quake').length, mode: snapshot.mode, fetchedAt: snapshot.fetchedAt };
  check('production USGS and RSS source metadata are real', response.ok() && snapshot.sources.some(source => source.id === 'usgs' && source.state === 'online') && report.news.seismic > 0);
  check('production golden path has no JavaScript or shader errors', report.errors.length === 0);
  await page.screenshot({ path: 'scripts/artifacts/production-live.png', fullPage: true });
  report.status = 'passed';
  console.log(JSON.stringify(report, null, 2));
} catch (error) {
  report.status = 'failed'; report.error = error.stack; console.error(error); process.exitCode = 1;
  await page.screenshot({ path: 'scripts/artifacts/production-failure.png', fullPage: true }).catch(() => {});
} finally {
  await writeFile('scripts/artifacts/production-report.json', JSON.stringify(report, null, 2));
  await browser.close();
}
